"""Xero Australia report parsing.

Reads Xero report exports (P&L, balance sheet) into normalised
structures for the lineage pipeline:

- code + tracking-aware: sums rows by (Account, Code), and exposes
  tracking option splits so Tracking Category options can map to
  departments or business units;
- sign-aware: rows come out positive for income and assets, negative for
  expenses, liabilities and equity. A flat Code/Account/Amount file is
  taken as already signed that way; the report layout Xero exports from
  Reports carries natural balances (expenses and liabilities positive,
  observed 5 September 2026) and is normalised by section;
- GST-aware: compares revenue with a supplied GST-exclusive control total.
  Without a usable control, the GST basis remains undetermined. Never feed a
  GST-inclusive series into ``pyfpa.au.monthly_gst`` as if exclusive.

This module parses report exports only. It holds no credentials and makes
no network call. Live access is a per-company connector generated by
``openfpa connector-scaffold``, whose credentials come from the host and
are never committed. See docs/recipes/xero-au.md.
"""

from __future__ import annotations

import csv
import re
from pathlib import Path

from pydantic import BaseModel, Field

from pyfpa.io.pl_csv import _parse_amount

_FIXTURES = Path(__file__).resolve().parent / "fixtures"

# Account-code ranges of a standard Australian Xero chart. Used only as a
# heuristic signal; unknown codes never block parsing.
_INCOME_CODES = range(200, 300)
_REVENUE_TYPE_KEYWORDS = ("sales", "revenue", "interest income")


class XeroRow(BaseModel):
    code: str = ""
    account: str
    amount: float
    tracking_option: str = ""  # empty = untracked / no category assigned


class XeroReport(BaseModel):
    rows: list[XeroRow] = Field(default_factory=list)

    def by_account(self) -> dict[str, float]:
        """{account: amount} summed across codes and tracking options."""
        totals: dict[str, float] = {}
        for row in self.rows:
            totals[row.account] = totals.get(row.account, 0.0) + row.amount
        return totals

    def by_tracking(self) -> dict[str, dict[str, float]]:
        """{tracking_option: {account: amount}} for department mapping."""
        splits: dict[str, dict[str, float]] = {}
        for row in self.rows:
            key = row.tracking_option or "(untracked)"
            splits.setdefault(key, {})
            splits[key][row.account] = splits[key].get(row.account, 0.0) + row.amount
        return splits


# Report-layout rows that are derived, not posted: skipped along with every
# "Total <section>" subtotal. Custom report layouts can rename these.
# ponytail: fixed label set; read the layout's own row types if a renamed
# derived row ever reaches by_account().
_DERIVED_ROWS = {"gross profit", "net profit", "net loss", "net assets", "total"}
# A section whose name matches carries natural-balance credits (expenses,
# cost of sales, liabilities, equity): its rows are negated so the report
# lands in this module's convention, income and assets positive.
_NEGATE_SECTION = re.compile(r"expense|cost|liabilit|equity", re.IGNORECASE)
_SECTION_LABELS = {
    "trading income", "income", "other income", "revenue", "cost of sales",
    "operating expenses", "expenses", "other expenses", "assets", "bank",
    "current assets", "non-current assets", "fixed assets", "liabilities",
    "current liabilities", "non-current liabilities", "equity",
}
# "Sales (200)": the shape Xero uses when a report shows account codes. A
# code is alphanumeric, at most 10 characters and carries a digit, so
# "Rent (Sydney)" keeps its parenthetical as part of the name.
_CODE_SUFFIX = re.compile(r"^(?P<name>.+) \((?P<code>[A-Za-z0-9]{1,10})\)$")

# English AU report headings: year, month/year or day/month/year. Tracking
# comparisons use option names in these columns and must not lose all but one.
_PERIOD_COLUMN = re.compile(
    r"(?:\d{4}|(?:\d{1,2} )?"
    r"(?:Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|"
    r"Jul(?:y)?|Aug(?:ust)?|Sep(?:t(?:ember)?)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?)"
    r" \d{4})",
    re.IGNORECASE,
)


def _split_code(label: str) -> tuple[str, str]:
    match = _CODE_SUFFIX.match(label)
    if match and any(ch.isdigit() for ch in match["code"]):
        return match["code"], match["name"]
    return "", label


def _read_flat_layout(rows: list[list[str]], fields: list[str], lines: list[int]) -> list[XeroRow]:
    """Columns Code, Account, Amount and optional Tracking Option, header first.

    The refusals read_pl_csv makes: an unnamed or repeated column, a row with
    more filled fields than the header (an unquoted thousands separator splits
    one amount in two, and the first half was read), and a filled row with no
    account (its amount was dropped). ``lines`` holds each row's line number.
    """
    if any(not name for name in fields):
        raise ValueError("unnamed Xero CSV columns")
    if len(fields) != len(set(fields)):
        raise ValueError(f"duplicate Xero CSV columns: {fields}")
    parsed: list[XeroRow] = []
    for line, raw in zip(lines[1:], rows[1:]):
        if any(cell.strip() for cell in raw[len(fields):]):
            raise ValueError(
                f"extra fields in Xero CSV row {line}; quote any amount that contains a comma"
            )
        record = dict(zip(fields, raw))
        account = (record.get("Account") or "").strip()
        if not account:
            raise ValueError(f"missing account in Xero CSV row {line}")
        parsed.append(
            XeroRow(
                code=(record.get("Code") or "").strip(),
                account=account,
                amount=_parse_amount(record.get("Amount")),
                tracking_option=(record.get("Tracking Option") or "").strip(),
            )
        )
    return parsed


def _read_report_layout(
    rows: list[list[str]], path: Path, *, tracking_comparison: bool = False
) -> list[XeroRow]:
    """The layout Xero exports from Reports, saved as CSV.

    Observed on the Demo Company (AU) Excel exports of the Profit and Loss
    and Balance Sheet, 5 September 2026. Rows 1 to 3 are the report name,
    the organisation and the period, then a blank row, then a header whose
    account column is labelled "Account": column A on the P&L, column B on
    the Balance Sheet, whose column A carries the top-level section. The
    column after "Account" is the reported period; comparative columns to
    its right are ignored, so export one period per file. A section row has
    no amounts. "Total <section>" subtotals and the derived Gross Profit,
    Net Profit and Net Assets rows are skipped, so every row returned is a
    posting account. Xero writes every amount as its natural balance, with
    expenses and liabilities positive; rows under a section whose name
    contains expense, cost, liabilit or equity are negated to reach this
    module's convention. Totals in the .xlsx are formulas whose cached
    value is 0, which is one more reason they are never read.
    """
    header_idx = next(
        (i for i, r in enumerate(rows) if "Account" in [c.strip() for c in r]), None
    )
    if header_idx is None:
        first = [c.strip() for c in rows[0]] if rows else []
        raise ValueError(
            f"expected columns 'Account' and 'Amount', or a Xero report header "
            f"row containing 'Account', got {first} in {path}"
        )
    header = [c.strip() for c in rows[header_idx]]
    name_idx = header.index("Account")
    amount_idx = name_idx + 1
    if amount_idx >= len(header) or not header[amount_idx]:
        raise ValueError(f"no period column after 'Account' in {path}")
    columns = header[amount_idx:]
    if tracking_comparison:
        if rows[0][0].strip().casefold() != "profit and loss" or name_idx != 0:
            raise ValueError("tracking_comparison requires the standard P&L report layout")
        folded = [column.casefold() for column in columns]
        if (
            any(not column or column in {"total", "(untracked)"} for column in folded)
            or len(set(folded)) != len(folded)
        ):
            raise ValueError(f"ambiguous tracking columns {columns} in {path}")
        amount_indices = range(amount_idx, len(header))
    elif any(_PERIOD_COLUMN.fullmatch(column) is None for column in columns):
        raise ValueError(
            f"unsupported report columns {columns} in {path}; "
            "export a standard report with year, month or date headings. "
            "For P&L tracking comparisons, set tracking_comparison=True after checking "
            "the source settings, or reshape to Code,Account,Amount,Tracking Option."
        )
    else:
        amount_indices = range(amount_idx, amount_idx + 1)
    sign = 1.0
    parsed: list[XeroRow] = []
    # Headings seen so far, so "Total X" is skipped only as the subtotal of an X
    # heading. A posting account that happens to start with "Total " (such as
    # "Total Tools Hire") was dropped with its amount; it is now refused.
    headings: set[str] = set()
    for raw in rows[header_idx + 1 :]:
        cells = [c.strip() for c in raw] + [""] * (len(header) - len(raw))
        label = cells[name_idx] or (cells[0] if name_idx else "")
        if not label:
            continue
        if label.lower() in _DERIVED_ROWS:
            continue
        if label.startswith("Total "):
            if label[len("Total ") :].casefold() not in headings:
                raise ValueError(
                    f"row {label!r} reads as a subtotal, but no {label[len('Total ') :]!r} "
                    f"heading precedes it in {path}; if it is a posting account, rename it"
                )
            continue
        blank_amounts = all(cell == "" for cell in cells[amount_idx:])
        # Some layouts head a deduction section "Less Operating Expenses".
        section = label.casefold().removeprefix("less ")
        if blank_amounts:
            headings.update({label.casefold(), section})
        section_row = blank_amounts and section in _SECTION_LABELS
        if tracking_comparison and not section_row and len(raw) != len(header):
            raise ValueError(f"tracking row {label!r} has the wrong number of columns in {path}")
        if tracking_comparison and not section_row and blank_amounts:
            raise ValueError(f"tracking row {label!r} has no amounts in {path}")
        if blank_amounts:
            if section in _SECTION_LABELS and sum(bool(cell) for cell in cells[:amount_idx]) == 1:
                sign = -1.0 if _NEGATE_SECTION.search(label) else 1.0
            continue
        code, account = _split_code(label)
        for index in amount_indices:
            option = header[index] if tracking_comparison else ""
            parsed.append(
                XeroRow(
                    code=code,
                    account=account,
                    amount=sign * _parse_amount(cells[index]),
                    tracking_option="" if option.casefold() == "unassigned" else option,
                )
            )
    return parsed


def read_xero_report(path: str | Path, *, tracking_comparison: bool = False) -> XeroReport:
    """Parse a Xero CSV export into an XeroReport.

    Two layouts are accepted. A flat file whose first row carries the
    columns Code, Account, Amount and optional Tracking Option (Code may be
    blank), and the report layout Xero exports from Reports, recognised by
    its title rows above a header containing "Account". See
    ``_read_report_layout`` for what the second one skips and normalises.

    Set tracking_comparison=True only for a standard P&L with one tracking
    option per amount column. This preserves all options, including names
    that resemble dates, and maps Unassigned to untracked. The default reads
    the first period only. Report settings must establish which mode applies;
    column names alone cannot do so. Flat files already carry Tracking Option
    and do not accept this flag.
    """
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Xero report not found: {p}")
    with p.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.reader(f)
        numbered = [(reader.line_num, row) for row in reader if any(c.strip() for c in row)]
    rows = [row for _, row in numbered]
    if not rows:
        raise ValueError(f"no rows parsed from {p}")
    fields = [c.strip() for c in rows[0]]
    if "Account" in fields and "Amount" in fields:
        if tracking_comparison:
            raise ValueError("tracking_comparison requires the standard P&L report layout")
        parsed = _read_flat_layout(rows, fields, [line for line, _ in numbered])
    else:
        parsed = _read_report_layout(rows, p, tracking_comparison=tracking_comparison)
    if not parsed:
        raise ValueError(f"no rows parsed from {p}")
    return XeroReport(rows=parsed)


def detect_gst_inclusive(
    report: XeroReport, control_total: float | None = None
) -> bool | None:
    """Best-effort check that a revenue series is GST-EXCLUSIVE.

    Returns True when the series looks GST-INCLUSIVE, False
    when it looks exclusive, None when undetermined. With a
    `control_total` (the entity's known GST-exclusive revenue for the
    period) the check compares tolerance: within 1% -> exclusive, within
    1% of 1.1x -> inclusive.

    Amounts alone cannot establish the GST basis. Without a usable control,
    return None and obtain the report settings or an independent control.
    A 1.1 comparison assumes wholly taxable sales at 10%; mixed GST treatments
    need a separate reconciliation. The result does not establish tax treatment.
    """
    income = [
        r.amount
        for r in report.rows
        if r.amount > 0
        and (
            (r.code.isdigit() and int(r.code) in _INCOME_CODES)
            or any(k in r.account.casefold() for k in _REVENUE_TYPE_KEYWORDS)
        )
    ]
    if not income:
        return None
    if control_total is not None and control_total > 0:
        total = sum(income)
        if abs(total - control_total) / control_total < 0.01:
            return False
        if abs(total - control_total * 1.1) / (control_total * 1.1) < 0.01:
            return True
        return None
    return None
